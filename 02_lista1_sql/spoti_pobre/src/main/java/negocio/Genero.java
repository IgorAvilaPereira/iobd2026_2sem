package negocio;

/**
 * Genero
 */
public class Genero {
    private int id;
    private String nome;
    private boolean ehGenero;
    
    
    public int getId() {
        return id;
    }
    public void setId(int id) {
        this.id = id;
    }
    public String getNome() {
        return nome;
    }
    public void setNome(String nome) {
        this.nome = nome;
    }
    public boolean isEhGenero() {
        return ehGenero;
    }
    public void setEhGenero(boolean ehGenero) {
        this.ehGenero = ehGenero;
    }

    

}
